import assert from "node:assert/strict";
import fs from "node:fs";
import { resolveProductName, withResolvedProductName, loadProductNameContext } from "../lib/product-name-resolver.mjs";
import { buildPublicProductsFullCandidate, loadPublicProductsPricingContext } from "./build-public-product-indexes-v1.mjs";
const context = loadProductNameContext();
const catalog = JSON.parse(fs.readFileSync("data/generated/public-products/catalog.json", "utf8")).products;
const { brandNameZh: ignoredBrandZh, displayNameQuality: ignoredQuality, ...newProduct } = catalog.find(x => x.id === "smokingpipes-724599");
newProduct.displayName = newProduct.displayNameEn;
assert.ok(newProduct && !context.names.has(newProduct.id));
const resolved = resolveProductName(newProduct);
assert.equal(resolved.brandNameZh, "彼得森");
assert.match(resolved.title, /^彼得森 /);
assert.match(resolved.title, /锈刻/);
assert.match(resolved.title, /牛头斗/);
assert.doesNotMatch(resolved.title, /Tobacco Pipe|undefined|null/);
assert.equal(resolved.quality, "ready");
const renamed = {...newProduct, id: "smokingpipes-future-id"};
const prefixed = resolveProductName({...renamed, displayNameEn: "Peterson: Rusticated Billiard Tobacco Pipe", shape: "Billiard"});
assert.equal(prefixed.title, "彼得森 锈刻 撞球斗");
assert.equal(resolveProductName({...renamed, source: "danish", displayName: "已确认的丹麦来源中文名"}).title, "已确认的丹麦来源中文名");
assert.equal(resolveProductName(renamed).title, resolved.title);
assert.deepEqual(resolveProductName(withResolvedProductName(renamed)), resolved);
assert.equal(resolveProductName({...renamed, brandName: "AKB", brandSlug: "akb"}).brandNameZh, null);
assert.equal(resolveProductName({...renamed, brandName: "Made Up Maker", brandSlug: "made-up", shape: null}).quality, "candidate");
assert.ok(resolveProductName({...renamed, brandName: "Made Up Maker", brandSlug: "made-up", shape: null}).warnings.includes("brandZhUnconfirmed"));
const unknown = resolveProductName({ id: "unknown-test", displayNameEn: "Untranslated model", brandName: "Unknown", shape: null });
assert.equal(unknown.quality, "fallback-original");
assert.equal(unknown.title, "Untranslated model");
const horn = resolveProductName({...renamed, displayNameEn: "Smooth Apple with Horn Stem Tobacco Pipe", shape: "Apple", finish: "Smooth"});
assert.match(horn.title, /with Horn Stem/);
assert.doesNotMatch(horn.title, /号角斗/);
const existing = catalog.filter(x => context.names.has(x.id));
for (const product of existing) assert.equal(resolveProductName(product).title, context.names.get(product.id).displayTitle);
const staging = JSON.parse(fs.readFileSync("data/products/unified-products-staging.json", "utf8"));
const row = staging.find(x => x.id === newProduct.id);
const candidate = buildPublicProductsFullCandidate([{...row, id: renamed.id}], await loadPublicProductsPricingContext());
assert.equal(candidate.catalog.products[0].brandNameZh, "彼得森");
assert.equal(candidate.catalog.products[0].displayName, resolved.title);
assert.equal(candidate.details[0].displayNameZh, resolved.title);
assert.equal(candidate.catalog.products[0].sourcePriceAmount, newProduct.sourcePriceAmount);
assert.equal(candidate.catalog.products[0].inventoryStatus, newProduct.inventoryStatus);
const after = catalog.map(x => withResolvedProductName(x));
const averageBytes = after.reduce((sum,x)=>sum+Buffer.byteLength(JSON.stringify(x)),0)/after.length;
console.log(JSON.stringify({status:"passed", historicalTitlesPreserved:existing.length, sample:resolved, averageRecordBytes:averageBytes}, null, 2));
assert.ok(averageBytes <= 1300, "Chinese fields must stay within the existing catalog performance budget");

